"""The patchbay as something derived, and a check that the saved one is still true.

`Patchbay/rig.qpwgraph` used to be hand-wired in qpwgraph's GUI, and it named
device profiles ("Audient iD14 Multichannel"), so changing interface or even
ALSA profile silently orphaned it: qpwgraph maintains its patch and dead links
just sat there. It is now generated by `generate_patchbay` from
`config/src/guitar_vocal.yaml` and `machines/<hostname>.yaml`, and
`test_the_committed_patchbay_is_what_generate_produces` holds the committed file
to that output, so a hand edit fails the suite. Two halves of the answer live
here (issue #54):

- `generate_patchbay` writes the file from roles and routes instead of by hand.
- `check_nodes` classifies the nodes a saved patchbay names against the live
  graph (returning a `NodeCheck`: `missing` and `not_running`), which is the
  cheap half and needs no machine file at all.

Everything is pure except `read_pw_dump`. A role resolving to a live port is
likewise a decision (`resolve_nodes`) over data that function fetched, so it can
be tested without PipeWire (quality principle 1).
"""

from __future__ import annotations

import json
import subprocess
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from typing import Any, Collection, Mapping
from xml.sax.saxutils import quoteattr

# What qpwgraph wrote in the committed file. Copied, not understood: whether
# qpwgraph checks it on load is not established.
PATCHBAY_VERSION = "0.9.9"

SUSHI_NODE = "sushi"

# The tuner, as PipeWire and qpwgraph name it. Both halves read off a real
# pw-dump taken with the rig running (tests/fixtures/pw-dump-rig.json), not
# inferred:
#
# - the node is `application.name` + "/" + `node.description`, which is exactly
#   the string qpwgraph wrote for it in the hand-made patchbay;
# - the port is `input_MONO`, singular. With `node.autoconnect` off (#52) fmit
#   negotiates the one port it actually wants instead of the stereo pair the
#   default source imposed on it -- so the hand-made patchbay's `input_FL` and
#   `input_FR` links name ports that no longer exist, and the tuner on that
#   machine has been fed by nothing at all since #52 landed.
TUNER_NODE = "PipeWire ALSA [fmit]/ALSA Capture [fmit]"
TUNER_PORT = "ALSA Capture [fmit]:input_MONO"

# Which role the tuner listens to. Not a port and not a position: #18's whole
# point is that the amp, the tuner, the panel and the recorder all key off the
# same declared channel, so a third channel is a declaration rather than an edit
# in five places.
GUITAR_ROLE = "guitar-in"
# Where the monitor mix leaves the machine. Named once, beside the guitar's role,
# because the converter of today's tones writes it as every rig's master output
# (convert.py); a second spelling is a master that goes nowhere.
MONITOR_ROLE = "monitor-out"

# pw-dump is a one-shot snapshot of the whole graph; a hung PipeWire is the only
# way it takes long, and a check that blocks forever is worse than one that fails.
PW_DUMP_TIMEOUT = 5.0


class PatchbayError(Exception):
    """Carries every problem found, not the first — see `RigSpec.validate`."""

    def __init__(self, problems: list[str]):
        self.problems = problems
        super().__init__("\n".join(problems))


# --- where a role goes -------------------------------------------------------


@dataclass(frozen=True)
class Dest:
    """A place on Sushi: a stereo bus pair, or a single channel.

    Sushi's own rule, which this mirrors rather than relaxes: a routing entry is
    one or the other, never both. `engine_bus: N` is channels 2N and 2N+1.
    """

    kind: str  # "bus" | "channel"
    index: int

    def channels(self) -> list[int]:
        return [2 * self.index, 2 * self.index + 1] if self.kind == "bus" else [self.index]


def bus(n: int) -> Dest:
    return Dest("bus", n)


def channel(n: int) -> Dest:
    return Dest("channel", n)


# One track's engine-side entries for a role. Paired together because a stereo
# role on channel-form routing is *two* entries (`engine_channel: 0` and `: 1`),
# and judging each alone refuses it against every one of them.
Route = tuple[Dest, ...]


def _index_problem(where: str, key: str, value: Any) -> str | None:
    # `type(...) is int`: a quoted "0" would otherwise die later in arithmetic
    # with a TypeError, and a negative index would generate
    # `sushi:audio_input_-2` without a word. bool is an int, so True is refused.
    if type(value) is int and value >= 0:
        return None
    return f"{where}: {key} must be a non-negative integer (got {value!r})"


def routes_from_rig(
    rig: Any,
) -> tuple[dict[str, list[Route]], dict[str, list[Route]]]:
    """role -> the routes it feeds on Sushi, and role -> the ones it takes, from a `RigSpec`.

    One `Route` per track (deduplicated), holding that track's entries for the
    role.

    Raises `PatchbayError` for any entry it cannot place, rather than skipping
    it. `RigSpec.validate()` accepts an entry carrying only `track_bus`, and
    dropping it here left a track named in `source:` with nothing wired while
    the generation went ahead for everyone else.
    """
    feeds: dict[str, list[Route]] = {}
    sinks: dict[str, list[Route]] = {}
    problems: list[str] = []
    for track in rig.tracks:
        for role, label, into in [
            (track.source, "inputs", feeds),
            (track.sink, "outputs", sinks),
        ]:
            if not role:
                continue
            route, found = track_route(track, label, role)
            problems += found
            if route and route not in into.setdefault(role, []):
                into[role].append(route)
    if problems:
        raise PatchbayError(problems)
    return feeds, sinks


def track_route(track: Any, label: str, role: str | None = None) -> tuple[Route, list[str]]:
    """One track's `inputs` or `outputs` as places on Sushi, and every entry
    that cannot be placed.

    The one reading of a track's routing, shared by the patchbay and by
    selftest's probes (probes.py), so the two can never disagree on a port.
    `role` only words the problem; a track with no role is read the same way.
    """
    route: list[Dest] = []
    problems: list[str] = []
    for entry in getattr(track, label):
        where = f"track {track.name!r}: {label} entry {entry}"
        has_bus, has_channel = "engine_bus" in entry, "engine_channel" in entry
        if has_bus and has_channel:
            problems.append(f"{where} mixes bus and channel forms")
        elif has_bus or has_channel:
            key = "engine_bus" if has_bus else "engine_channel"
            problem = _index_problem(where, key, entry[key])
            if problem:
                problems.append(problem)
            else:
                route.append((bus if has_bus else channel)(entry[key]))
        else:
            taker = f"the role {role!r}" if role else "the track"
            problems.append(
                f"{where} names no engine_bus or engine_channel, so which "
                f"Sushi {label[:-1]} {taker} takes is unknown"
            )
    # One place on Sushi named twice is one port. A v2 rig's mono channel does
    # exactly that — engine channel 0 into both halves of its track
    # (rigfile.py) — and counted twice it would ask the role for two ports.
    return tuple(dict.fromkeys(route)), problems


def _as_routes(value: Any) -> list[Route]:
    """Accept a bare `Dest` for a one-entry route, which is what most callers mean."""
    return [(r,) if isinstance(r, Dest) else tuple(r) for r in value]


# --- generation --------------------------------------------------------------


@dataclass(frozen=True)
class Link:
    out_node: str
    out_port: str
    in_node: str
    in_port: str


def generate_patchbay(
    roles: Mapping[str, list[str]],
    feeds: Mapping[str, Any],
    sinks: Mapping[str, Any] | None = None,
    *,
    mono_to_stereo: Collection[str] = (),
    nodes: Mapping[str, str] | None = None,
    sushi_node: str = SUSHI_NODE,
    tuner_role: str | None = None,
    name: str = "rig",
) -> str:
    """qpwgraph patchbay XML from role -> ports and role -> where on Sushi.

    Raises `PatchbayError` listing every problem; never returns a patchbay it is
    unsure of, because an unwired track looks exactly like a working one.

    `feeds` and `sinks` map a role to its routes (see `routes_from_rig`); a bare
    list of `Dest` is accepted as one-entry routes.

    Pairing, which is the part worth being exact about:

    - A two-port role into a bus is left to right, in the order listed.
    - A one-port role into a bus is an error *unless the role is in
      `mono_to_stereo`*, in which case the port feeds both halves. Duplication
      is declared, never inferred from the port count: the committed patchbay
      has it only on the dead `Pro` profile, and the live `Multichannel`
      profile wires one input per channel. A rule inferred from one of them was
      wrong for the other, and silently.
    - A channel-form route pairs ports with its entries in order, so a stereo
      role works with `engine_channel: 0` and `engine_channel: 1`.
    - Anything else (three ports into a bus, a count that does not match the
      entries) is an error rather than a pick: choosing which port to drop, or
      summing two physical inputs into one, is the near-miss recorded in
      `amp_patchbay`.
    - Two different ports reaching the same Sushi input is an error for the same
      reason. Fanning one output to several places is not: Sushi outputs may go
      to monitors and headphones at once.

    `nodes` maps a port to the node name qpwgraph shows for it. The machine file
    holds only ports (`Audient iD14:capture_AUX0`), but the saved file keys links
    on node *and* port, and for an ALSA device the node is the profile
    ("Audient iD14 Multichannel") — which the port name does not contain and
    which is precisely what changes between profiles. Without it the node falls
    back to the port's own client name, which is right for Sushi and not for a
    device.

    `tuner_role` taps that role's port into the tuner as well as into Sushi.
    Without it a generated patchbay is complete except for the tuner, and
    replacing the hand-made file with one would leave `fmit` deaf — the kind of
    quiet regression a generator is supposed to remove. The tuner follows a
    *role*, so it moves with the guitar rather than sitting on a port index.
    """
    nodes = nodes or {}
    sinks = sinks or {}
    mono = set(mono_to_stereo)
    problems: list[str] = []

    def node_of(port: str) -> str:
        return nodes.get(port) or port.partition(":")[0]

    # Sushi input index -> physical ports feeding it, with the role that asked.
    into: dict[int, dict[str, str]] = {}
    # Sushi output index -> physical ports it feeds.
    out_of: dict[int, dict[str, str]] = {}
    # Physical playback port -> the Sushi outputs that feed it.
    playback: dict[str, set[int]] = {}

    for role, value in feeds.items():
        ports = roles.get(role)
        if ports is None:
            problems.append(_unknown_role(role, roles, "feeds a track"))
            continue
        for route in _as_routes(value):
            pairs = _pair_source(role, ports, route, role in mono)
            if isinstance(pairs, str):
                problems.append(pairs)
                continue
            for index, port in pairs:
                into.setdefault(index, {}).setdefault(port, role)

    for role, value in sinks.items():
        ports = roles.get(role)
        if ports is None:
            problems.append(_unknown_role(role, roles, "takes a track's output"))
            continue
        for route in _as_routes(value):
            pairs = _pair_sink(role, ports, route)
            if isinstance(pairs, str):
                problems.append(pairs)
                continue
            for index, port in pairs:
                out_of.setdefault(index, {}).setdefault(port, role)
                playback.setdefault(port, set()).add(index)

    for index, ports in sorted(into.items()):
        if len(ports) > 1:
            who = ", ".join(f"{p!r} (role {r!r})" for p, r in ports.items())
            problems.append(
                f"{sushi_node}:audio_input_{index} would be fed by more than one "
                f"port: {who} — they would be summed into one input"
            )
    for port, indexes in sorted(playback.items()):
        if len(indexes) > 1:
            outs = ", ".join(f"{sushi_node}:audio_output_{i}" for i in sorted(indexes))
            problems.append(f"playback port {port!r} would be fed by {outs} — summed")

    tuner_port: str | None = None
    if tuner_role is not None:
        refusal = tuner_problem(roles, tuner_role)
        if refusal:
            problems.append(refusal)
        else:
            tuner_port = roles[tuner_role][0]

    if problems:
        raise PatchbayError(problems)

    # Sorted at both levels so the bytes depend on the rig, not on which track
    # happens to come first in rig.yaml. Only an output can fan out to several
    # ports, so that is where dict order would otherwise leak.
    links: list[Link] = []
    for index, ports in sorted(into.items()):
        for port in sorted(ports):
            links.append(
                Link(node_of(port), port, sushi_node, f"{sushi_node}:audio_input_{index}")
            )
    for index, ports in sorted(out_of.items()):
        for port in sorted(ports):
            links.append(
                Link(sushi_node, f"{sushi_node}:audio_output_{index}", node_of(port), port)
            )
    if tuner_port is not None:
        links.append(Link(node_of(tuner_port), tuner_port, TUNER_NODE, TUNER_PORT))
    return render_patchbay(links, name)


def _unknown_role(role: str, roles: Mapping[str, list[str]], doing: str) -> str:
    known = ", ".join(repr(r) for r in sorted(roles)) or "none"
    return f"role {role!r} {doing} but the machine file does not define it (it defines: {known})"


def _pair_source(
    role: str, ports: list[str], route: Route, mono: bool
) -> list[tuple[int, str]] | str:
    """(Sushi input index, physical port) pairs, or why the role cannot feed here."""
    if mono and len(ports) != 1:
        return (
            f"role {role!r} declares mono_to_stereo but has {len(ports)} ports; "
            "it duplicates one port, so it needs exactly one"
        )
    pairs: list[tuple[int, str]] = []
    for dest in (d for d in route if d.kind == "bus"):
        chans = dest.channels()
        if len(ports) == 1 and mono:
            pairs += [(c, ports[0]) for c in chans]
        elif len(ports) == 1:
            return (
                f"role {role!r} has 1 port but feeds bus {dest.index}, a stereo "
                "pair. If one mono source should drive both halves, declare it: "
                f"{role}: {{ports: [{ports[0]!r}], mono_to_stereo: true}}. "
                "Otherwise list two ports"
            )
        elif len(ports) == 2:
            pairs += list(zip(chans, ports))
        else:
            return (
                f"role {role!r} has {len(ports)} ports but feeds bus {dest.index}, "
                "a stereo pair; give it two (left, right) or one with mono_to_stereo"
            )
    channels = [d for d in route if d.kind == "channel"]
    if channels:
        if len(ports) == len(channels):
            pairs += [(d.index, p) for d, p in zip(channels, ports)]
        elif len(ports) == 1 and mono:
            pairs += [(d.index, ports[0]) for d in channels]
        else:
            return (
                f"role {role!r} has {len(ports)} port(s) but this track routes it "
                f"to {len(channels)} engine channel(s) "
                f"({', '.join(str(d.index) for d in channels)}); each channel takes "
                "one port, so the counts must match"
            )
    return pairs


def _pair_sink(role: str, ports: list[str], route: Route) -> list[tuple[int, str]] | str:
    """(Sushi output index, physical port) pairs, or why the role cannot take it."""
    pairs: list[tuple[int, str]] = []
    for dest in (d for d in route if d.kind == "bus"):
        if len(ports) != 2:
            # No mono-into-stereo rule on the way out. Folding two channels into
            # one port is a mix-down, and which mix-down is a decision nobody has
            # made.
            return (
                f"role {role!r} has {len(ports)} port(s) but takes bus "
                f"{dest.index}, a stereo pair, which needs 2"
            )
        pairs += list(zip(dest.channels(), ports))
    channels = [d for d in route if d.kind == "channel"]
    if channels:
        if len(ports) != len(channels):
            return (
                f"role {role!r} has {len(ports)} port(s) but this track takes "
                f"{len(channels)} engine channel(s) "
                f"({', '.join(str(d.index) for d in channels)}), which needs "
                f"{len(channels)}"
            )
        pairs += [(d.index, p) for d, p in zip(channels, ports)]
    return pairs


# The shape qpwgraph itself writes, including the blank line after the closing
# tag and the attribute order. qpwgraph reads this file, so it is matched rather
# than improved.
_HEAD = '<!DOCTYPE patchbay>\n<patchbay name={name} version={version}>\n <items>\n'
_ITEM = (
    '  <item node-type="pipewire" port-type="pipewire-audio">\n'
    '   <output node={out_node} port={out_port}/>\n'
    '   <input node={in_node} port={in_port}/>\n'
    '  </item>\n'
)
_TAIL = ' </items>\n</patchbay>\n\n'


def patchbay_for(
    rig: Any,
    machine: Any,
    dump: str | None,
    *,
    tuner: bool = True,
    rig_name: str = "rig",
    machine_name: str = "machine",
) -> tuple[str, list[str]]:
    """The patchbay for `rig` on `machine`, and the warnings worth printing.

    One function for `patchbay generate` and for `up` on a v2 rig (#30), so the
    two cannot wire a channel differently. `dump` is the live graph's pw-dump
    text, which resolves each port to the node qpwgraph will show for it; None
    is the offline form, approximate for an ALSA device and for diffing only.
    Pure given its arguments: every effect (reading the files, running
    pw-dump) is the caller's. Raises `PatchbayError` with every problem.

    The tuner follows the guitar role rather than a port, so it moves with the
    channel. Decided before the live graph is read, because the tuner's port
    has to be resolved alongside the tracks': left out of `resolve_nodes`, the
    tap was written with the port's client name instead of the live ALSA
    profile, which qpwgraph never matches, giving a deaf tuner in a file that
    generated cleanly. A guitar role the tuner cannot tap is a warning, not a
    refusal: a reason to have no tuner tap, not a reason to have no patchbay.
    """
    feeds, sinks = routes_from_rig(rig)
    if not feeds and not sinks:
        # An empty patchbay written without comment is the silent failure this
        # exists to end: nothing wired, and nothing says why.
        raise PatchbayError([
            f"{rig_name}: no track names a source or sink role, so there is "
            "nothing to generate"
        ])
    roles = machine.role_ports()
    warnings: list[str] = []
    tuner_role = GUITAR_ROLE if tuner else None
    refusal = tuner_problem(roles, tuner_role) if tuner_role else None
    if refusal:
        warnings.append(
            f"{machine_name}: {refusal}. The generated patchbay has no tuner "
            "tap, so fmit will hear nothing"
        )
        tuner_role = None
    nodes = None
    if dump is not None:
        sources = set(feeds) | ({tuner_role} if tuner_role else set())
        nodes, problems = resolve_nodes(roles, sources, set(sinks), live_port_nodes(dump))
        if problems:
            raise PatchbayError(problems)
    xml = generate_patchbay(
        roles, feeds, sinks, mono_to_stereo=machine.mono_roles(), nodes=nodes,
        tuner_role=tuner_role,
    )
    return xml, warnings


def render_patchbay(links: list[Link], name: str = "rig") -> str:
    # quoteattr, not an f-string: a device description with an ampersand or a
    # quote in it is a valid node name and must not corrupt the file.
    out = [_HEAD.format(name=quoteattr(name), version=quoteattr(PATCHBAY_VERSION))]
    for link in links:
        out.append(
            _ITEM.format(
                out_node=quoteattr(link.out_node), out_port=quoteattr(link.out_port),
                in_node=quoteattr(link.in_node), in_port=quoteattr(link.in_port),
            )
        )
    out.append(_TAIL)
    return "".join(out)


def parse_patchbay(xml: str) -> list[Link]:
    """The links in a saved patchbay, in file order.

    A real XML parse, unlike `amp_patchbay`'s regex: a check that misreads the
    file reports the wrong nodes as missing, and the cost of that is the user
    deleting links that were fine.
    """
    try:
        root = ET.fromstring(xml)
    except ET.ParseError as exc:
        raise PatchbayError([f"not a readable patchbay: {exc}"]) from exc
    links = []
    for item in root.iter("item"):
        out, inp = item.find("output"), item.find("input")
        if out is None or inp is None:
            raise PatchbayError(["an <item> is missing its <output> or <input>"])
        links.append(
            Link(
                out.get("node", ""), out.get("port", ""),
                inp.get("node", ""), inp.get("port", ""),
            )
        )
    return links


# --- what is actually there --------------------------------------------------

_NODE = "PipeWire:Interface:Node"
_PORT = "PipeWire:Interface:Port"


def _props(obj: dict) -> dict:
    return (obj.get("info") or {}).get("props") or {}


def _objects(dump: str) -> list[dict]:
    try:
        parsed = json.loads(dump)
    except ValueError as exc:
        raise PatchbayError([f"pw-dump did not produce JSON: {exc}"]) from exc
    if not isinstance(parsed, list):
        raise PatchbayError(["pw-dump output is not a list of objects"])
    return [o for o in parsed if isinstance(o, dict)]


def _display_name(props: dict) -> str | None:
    # description, then nick, then name: what qpwgraph's node labels look like
    # for the one device whose labels we have ("Audient iD14 Multichannel" reads
    # as a description). The order is inferred from that, not read from
    # qpwgraph's source.
    for key in ("node.description", "node.nick", "node.name"):
        if props.get(key):
            return props[key]
    return None


def nodes_by_id(dump: str) -> dict[int, dict]:
    """Every live node's properties, keyed by its PipeWire object id.

    `live_node_names` answers "does this saved name exist". This hands back the
    properties themselves, for the questions `doctor` asks of them: which node
    clocks the rig (`node.driver-id`), and what Sushi asked the graph for
    (`node.force-quantum`, `node.force-rate`).

    It lives here rather than in `doctor` because this module owns the pw-dump
    format, and a second reader of it would drift from this one.
    """
    found: dict[int, dict] = {}
    for obj in _objects(dump):
        if obj.get("type") == _NODE and isinstance(obj.get("id"), int):
            found[obj["id"]] = _props(obj)
    return found


def live_node_names(dump: str) -> set[str]:
    """Every name a live node answers to: description, nick, node.name, and each
    of those behind the `<application.name>/` prefix qpwgraph shows for a client.

    Settled against a real `pw-dump` from the rig (`tests/fixtures/pw-dump-rig.json`)
    rather than inferred. Two things that capture established:

    - **`node.description` is qpwgraph's label.** `'Audient iD14 Multichannel'`
      and `'Audient iD14 Analog Surround 4.0'` are exactly the `node=` strings in
      the committed patchbay, while `node.nick` is `'Audient iD14'` -- the *port
      alias* prefix, identical across every profile of the device, which is why
      a port alias alone cannot identify a node.
    - **The slashed form is a composition**, not a mystery: `fmit` carries
      `application.name = 'PipeWire ALSA [fmit]'` and
      `node.description = 'ALSA Capture [fmit]'`, which join to give exactly the
      `'PipeWire ALSA [fmit]/ALSA Capture [fmit]'` the patchbay names.

    Deliberately generous: a saved name matching any of these counts as live.
    That errs towards missing a stale link rather than inventing one, which suits
    a check people stop reading if it cries wolf. The slashed form is composed
    against the nick and `node.name` as well as the description, because a node
    can carry an `application.name` and no description at all -- this capture's
    `speech-dispatcher-dummy` does -- and composing only against the description
    would leave that node's saved name unmatchable for ever.

    Raises if the graph holds no nodes at all. PipeWire answering with nothing
    is a check that could not look, and reporting every link stale on that would
    read as a finding when it is not.
    """
    names: set[str] = set()
    found_node = False
    for obj in _objects(dump):
        if obj.get("type") != _NODE:
            continue
        found_node = True
        props = _props(obj)
        own = [props[k] for k in ("node.description", "node.nick", "node.name") if props.get(k)]
        names.update(own)
        app = props.get("application.name")
        if app:
            names.update(f"{app}/{name}" for name in own)
    if not found_node:
        raise PatchbayError(["the PipeWire graph holds no nodes — cannot tell what is missing"])
    return names


@dataclass(frozen=True)
class LivePort:
    node: str
    # PipeWire's `port.direction`, "in" or "out", from the node's side: a
    # capture port is an "out" (the node produces audio), a playback port an "in".
    direction: str | None


def live_port_nodes(dump: str) -> dict[str, list[LivePort]]:
    """Port alias -> the ports that carry it, with their node and direction.

    A list because nothing makes an alias unique: `Audient iD14:capture_AUX0` is
    the same under every ALSA profile of the device, so two profiles live at once
    would both answer to it.
    """
    objects = _objects(dump)
    node_name = {
        o.get("id"): _display_name(_props(o)) for o in objects if o.get("type") == _NODE
    }
    found: dict[str, list[LivePort]] = {}
    for obj in objects:
        if obj.get("type") != _PORT:
            continue
        props = _props(obj)
        alias, owner = props.get("port.alias"), node_name.get(props.get("node.id"))
        if alias and owner:
            port = LivePort(owner, props.get("port.direction"))
            if port not in found.setdefault(alias, []):
                found[alias].append(port)
    return found


def resolve_nodes(
    roles: Mapping[str, list[str]],
    sources: Collection[str],
    sinks: Collection[str],
    port_nodes: Mapping[str, list[LivePort]],
) -> tuple[dict[str, str], list[str]]:
    """port -> node name for every port of the roles in use, plus what failed.

    Only roles in `sources` or `sinks`: a machine file may describe hardware
    that is unplugged today, and that is only a problem if a track needs it.

    A source role's ports must be PipeWire outputs (capture) and a sink role's
    inputs (playback). Without that, a playback port named in a source role
    resolves cleanly and the patchbay asks for a link PipeWire can never make,
    which looks exactly like a working file.

    This is the issue's "a role that resolves to no live port fails loudly,
    naming the role and what it looked for".
    """
    resolved: dict[str, str] = {}
    problems: list[str] = []
    wanted = {r: "out" for r in sources}
    for role in sinks:
        if role in wanted:
            problems.append(f"role {role!r} is used as both a source and a sink")
        wanted[role] = "in"
    for role in sorted(set(wanted) & set(roles)):
        expected = wanted[role]
        use = "source (capture)" if expected == "out" else "sink (playback)"
        for port in roles[role]:
            found = port_nodes.get(port, [])
            if not found:
                problems.append(
                    f"role {role!r}: no live port with alias {port!r} — is the "
                    "interface connected, and is this its current name?"
                )
                continue
            right = [p for p in found if p.direction == expected]
            if not right:
                seen = ", ".join(sorted({repr(p.direction) for p in found}))
                problems.append(
                    f"role {role!r}: port {port!r} is used as a {use} and so must "
                    f"have direction {expected!r}, but the live graph says {seen}"
                )
            elif len(right) > 1:
                owners = ", ".join(repr(p.node) for p in right)
                problems.append(
                    f"role {role!r}: port {port!r} exists on more than one node "
                    f"({owners}); cannot tell which one the patchbay should name"
                )
            else:
                resolved[port] = right[0].node
    return resolved, problems


@dataclass(frozen=True)
class NodeCheck:
    """What the live graph says about each node a saved patchbay names.

    Three states, because "absent" means two different things and only one of
    them is a fault. Present is a name that matches a live node; the other two
    are the fields below. Collapsing them is what made this check's first real
    run report three dead nodes when one was dead, and a check that cries wolf
    on a healthy rig stops being read.

    There was briefly a fourth, `unevaluated`, for the `<client>/<node>` form
    this could not match. It is gone, and its going is the point: a bucket that
    neither passes nor fails is only honest while the form really is unknown,
    and `live_node_names` composes that form now. Left in, it answered "cannot
    tell" for a link naming a client that is genuinely gone -- the exact failure
    the check exists to catch, excused by the machinery meant to avoid crying
    wolf.
    """

    missing: dict[str, list[Link]]
    not_running: dict[str, list[Link]]


# Nodes the rig itself provides, which exist only while it is running. Taken
# from `top.CHILD_NODES` rather than restated, so the two cannot drift.
#
# They need their own answer. A `patchbay check` run with the rig down reported
# `sushi` as "definitely not in the graph" alongside a genuinely dead ALSA
# profile, and said three nodes were gone when one was -- which buries the only
# finding that mattered. "Not running" and "no longer exists" are different
# facts and the check now says which it means.
def rig_node_names() -> set[str]:
    from .top import CHILD_NODES

    return {name for names in CHILD_NODES.values() for name in names}


def _names_child(child: str, node: str) -> bool:
    """Whether `node` is a name for the rig process `child`.

    Not equality, because neither qpwgraph nor PipeWire always writes the rig's
    own name for the node. Three forms, and only three, every one of them read
    off the committed patchbay or the capture:

    - `sushi`, `NAM`, `fmit` -- the name itself.
    - `ALSA Capture [fmit]`, `PipeWire ALSA [fmit]/ALSA Capture [fmit]` -- the
      name bracketed, which is what PipeWire's ALSA layer does with it.
    - `alsa_capture.fmit` -- the name as the last dotted segment.

    Narrow on purpose. An earlier version matched on any non-alphanumeric
    boundary, which excused a dead interface called `NAM Keys` or `fmit-old` as
    "the rig is not running", and let an incidental mention in a live node name
    (`sushi monitor`) declare the child up. If some future form is missed, the
    saved name falls to `missing`: a visible wrong answer rather than a silent
    excuse, which is the right way round for this check.
    """
    return (
        node == child
        or f"[{child}]" in node
        or node.endswith(f".{child}")
    )


def _rig_child(node: str, rig_nodes: Collection[str]) -> str | None:
    """Which rig process a saved name refers to, or None if it names a device."""
    for child in sorted(rig_nodes):
        if _names_child(child, node):
            return child
    return None


def tuner_problem(roles: Mapping[str, list[str]], tuner_role: str) -> str | None:
    """Why the tuner cannot tap `tuner_role`, or None if it can.

    Stated once and used twice: `generate_patchbay` turns it into a refusal,
    because a library that guesses is worse than one that stops, and the command
    turns it into a warning and leaves the tap out, because a stereo guitar is a
    reason to have no tuner tap and not a reason to have no patchbay.
    """
    ports = roles.get(tuner_role)
    if ports is None:
        return _unknown_role(tuner_role, roles, "feeds the tuner")
    if len(ports) != 1:
        # The tuner has one input port, so two would be summed into it. Which of
        # a stereo pair to tune is a judgement, and this module refuses those
        # rather than picking -- see `_pair_source`.
        return (
            f"role {tuner_role!r} has {len(ports)} ports but the tuner has one "
            f"input ({TUNER_PORT}); give the tuner a role with a single port"
        )
    return None


def check_nodes(
    links: list[Link], live: set[str], rig_nodes: set[str] | None = None
) -> NodeCheck:
    """Classify each node the links name against the live node names.

    Two answers, not one, because a node can be absent for two different
    reasons and only one of them is the user's problem:

    - **missing** — a name that should be there whatever the rig is doing, and
      is not. A dead ALSA profile, or a client that has gone away. This is the
      finding, and it is what makes the check exit 1.
    - **not_running** — a name for a rig process that has no live node at all,
      so absent means the rig is down. Not a fault, and reporting it as one
      drowns the finding.

    "Rig process with no live node at all" is the careful part. A saved name is
    only excused while the process it names is absent: with the rig up, the
    committed patchbay's bare `fmit` matches nothing, because under PipeWire's
    ALSA layer the tuner presents as `ALSA Capture [fmit]`. That link is dead
    and gets reported, while the same name with the tuner stopped does not.

    A link with both ends in a bad state appears under each. Keyed by node
    because that is what the user acts on: a missing node is one profile or one
    app, however many links it carries.
    """
    rig = rig_nodes if rig_nodes is not None else rig_node_names()
    # Which rig processes are up, by their own name appearing in any live node
    # name. Decided once per check rather than per link.
    running = {
        child for child in rig if any(_names_child(child, name) for name in live)
    }
    missing: dict[str, list[Link]] = {}
    not_running: dict[str, list[Link]] = {}
    for link in links:
        for node in (link.out_node, link.in_node):
            if node in live:
                continue
            child = _rig_child(node, rig)
            if child is not None and child not in running:
                bucket = not_running.setdefault(node, [])
            else:
                bucket = missing.setdefault(node, [])
            if link not in bucket:
                bucket.append(link)
    return NodeCheck(missing, not_running)


